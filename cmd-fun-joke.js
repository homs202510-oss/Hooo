const keys = Object.keys(jokes);
const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];

module.exports = {
    name: 'نكتة',
    aliases: ['joke', 'نكت', 'ضحك'],
    desc: 'نكت عشوائية',
    async run(ctx) {
        // اختار تصنيف عشوائي
        const cat = pick(keys);
        const list = jokes[cat];

        // اختار 3 نكت
        const shuffled = [...list].sort(() => Math.random() - 0.5).slice(0, Math.min(3, list.length));
        const content = shuffled.map((j, i) => `  ${i + 1}. ${j}`).join('\n\n');

        // تقييم عشوائي
        const rate = (Math.random() * 5 + 5).toFixed(1);

        await ctx.card('نكتة عشوائية', [
            { emoji: '🎭', title: `التصنيف: ${cat}`, content: content },
            { emoji: '⭐', title: 'التقييم', content: ` ${rate}/10 🎯` },
            { emoji: '💡', title: 'ملاحظة', content: ' كل مرة يطلعلك تصنيف مختلف!' },
        ]);
    }
};
