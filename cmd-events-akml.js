const rewardMap = { سهل: 50, متوسط: 60, صعب: 75, خارق: 100 };
const penaltyMap = { سهل: 50, متوسط: 50, صعب: 50, خارق: 50 };
const timeMap = { سهل: 15000, متوسط: 20000, صعب: 25000, خارق: 35000 };

// ========== دالة الإرسال الموحدة ==========
async function sendMessage(sock, chatId, lines, quoted = null, mentions = []) {
    if (!Array.isArray(lines)) lines = [lines];
    let msg = `📝 فـعـالـيـة أكـمـل الـجـمـلـة 📝\n━━━━━━━━━━━━━━━━━━━━\n`;
    for (const line of lines) msg += `${line}\n`;
    msg += `━━━━━━━━━━━━━━━━━━━━\n𝘽𝙔┇𝑷𝑯𝑨𝑵𝑻𝑶𝑴 ❤️`;
    await sock.sendMessage(chatId, { text: msg, mentions }, { quoted });
}

module.exports = {
    command: 'اكمل',
    description: '📝 أكمل الجملة الناقصة (سهل/متوسط/صعب/خارق)',
    usage: '.اكمل [سهل|متوسط|صعب|خارق]',
    category: 'فعاليات',

    async execute(sock, msg) {
        const chatId = msg.key.remoteJid;
        try {
            const sender = msg.key.participant || msg.participant || msg.key.remoteJid;
            const points = loadJSON(pointsPath);

            const body = msg.message?.conversation || msg.message?.extendedTextMessage?.text || '';
            const parts = body.trim().split(/\s+/);
            const inputLevel = (parts[1] || 'سهل').trim();

            const validLevels = ['سهل', 'متوسط', 'صعب', 'خارق'];
            if (!validLevels.includes(inputLevel)) {
                await sendMessage(sock, chatId, [
                    '❌ *المستوى غير صحيح!*',
                    '📖 المستويات المتاحة: سهل، متوسط، صعب، خارق',
                    '💡 مثال: .اكمل سهل'
                ], msg, [sender]);
                return;
            }

            const levelSentences = sentences[inputLevel];
            const sentence = levelSentences[Math.floor(Math.random() * levelSentences.length)];
            const startTime = Date.now();

            await sendMessage(sock, chatId, [
                `🔍 *أكمل الجملة التالية:*`,
                ``,
                `${sentence.text}`,
                ``,
                `⏳ الوقت: ${timeMap[inputLevel] / 1000} ثانية`,
                `💰 الجائزة: ${rewardMap[inputLevel]} نقطة`,
                `⚡ مكافأة السرعة: +20 نقطة إذا أجبت خلال 5 ثوانٍ`,
                `💔 الخسارة: -${penaltyMap[inputLevel]} نقطة`,
                `🏆 المستوى: ${inputLevel}`,
                ``,
                `📝 اكتب الإجابة (كلمة أو أكثر)`
            ], msg, [sender]);

            let finished = false;

            const handler = async ({ messages }) => {
                if (finished) return;
                for (const m of messages) {
                    if (m.key.remoteJid !== chatId) continue;
                    const winner = m.key.participant || m.participant || m.key.remoteJid;
                    if (winner === sock.user.id) continue;
                    const txt = m.message?.conversation || m.message?.extendedTextMessage?.text || '';
                    if (!txt.trim()) continue;

                    const cleaned = txt.trim().toLowerCase();
            // مقارنة الإجابة (يمكن أن تكون عدة كلمات)
                    if (cleaned === sentence.answer.toLowerCase()) {
                        finished = true;
                        clearTimeout(timeout);
                        sock.ev.off('messages.upsert', handler);

                        const elapsed = (Date.now() - startTime) / 1000;
                        let reward = rewardMap[inputLevel];
                        if (elapsed <= 5) reward += 20;

                        points[winner] = (points[winner] || 0) + reward;
                        saveJSON(pointsPath, points);

                        await sendMessage(sock, chatId, [
                            `🎉 *إجابة صحيحة!*`,
                            ``,
                            `🏆 @${winner.split('@')[0]}`,
                            `📝 الإجابة: *${sentence.answer}*`,
                            `⏱️ الزمن: ${elapsed.toFixed(1)} ثانية`,
                            `⭐ +${reward} نقطة ${elapsed <= 5 ? '(⚡ سرعة!)' : ''}`,
                            `💰 نقاطك: ${points[winner]}`,
                            ``,
                            `🥳 تهانينا!`
                        ], m, [winner]);
                        return;
                    }
                }
            };

            sock.ev.on('messages.upsert', handler);

            const timeout = setTimeout(async () => {
                if (finished) return;
                finished = true;
                sock.ev.off('messages.upsert', handler);

                const penalty = penaltyMap[inputLevel];
                points[sender] = Math.max(0, (points[sender] || 0) - penalty);
                saveJSON(pointsPath, points);

                await sendMessage(sock, chatId, [
                    `⏰ *انتهى الوقت!*`,
                    ``,
                    `📝 الإجابة الصحيحة: *${sentence.answer}*`,
                    ``,
                    `💔 تم خصم ${penalty} نقطة من @${sender.split('@')[0]}`,
                    `💰 نقاطك: ${points[sender]}`,
                    ``,
                    `📌 حاول مرة أخرى بـ .اكمل`
                ], msg, [sender]);
            }, timeMap[inputLevel]);

        } catch (error) {
            console.error('✗ خطأ في أمر اكمل:', error);
            await sendMessage(sock, msg.key.remoteJid, [
                '❌ حدث خطأ أثناء تنفيذ الأمر.',
                '📌 حاول مرة أخرى لاحقاً.'
            ], msg);
        }
    }
};