// ========== الحروف المسموح بها ==========
const allowedLetters = ['ا', 'ب', 'ت', 'ج', 'ح', 'خ', 'د', 'ر', 'ز', 'س', 'ش', 'ط', 'ع', 'ف', 'ك', 'ل', 'م', 'ن', 'ه', 'و', 'ي'];

// ========== دالة الإرسال ==========
async function sendMessage(sock, chatId, lines, quoted = null, mentions = []) {
    if (!Array.isArray(lines)) {
        lines = [lines];
    }

    let msg = `🔤 فـعـالـيـة الـحـروف 🔤\n`;
    msg += `━━━━━━━━━━━━━━━━━━━━\n`;
    for (const line of lines) {
        msg += `${line}\n`;
    }
    msg += `━━━━━━━━━━━━━━━━━━━━\n`;
    msg += `𝘽𝙔┇𝑷𝑯𝑨𝑵𝑻𝑶𝑴 ❤️`;
    await sock.sendMessage(chatId, { text: msg, mentions }, { quoted: quoted });
}

module.exports = {
    command: ['حرف'],
    description: '🔤 فعالية الحروف مع التحقق من شخصيات الأنمي',
    usage: '.حرف',
    category: 'فعاليات',
    example: '.حرف',

    async execute(sock, msg) {
        const chatId = msg.key.remoteJid;
        try {
            const sender = msg.key.participant || msg.participant || msg.key.remoteJid;
            const points = loadJSON(pointsPath);

            const letter = allowedLetters[Math.floor(Math.random() * allowedLetters.length)];

            // إرسال السؤال
            const lines = [
                `🔤 *اكتب شخصية أنمي تبدأ بحرف:*`,
                ``,
                `📌 الحرف: *${letter}*`,
                ``,
                `⏳ الوقت: 30 ثانية`,
                `💰 الجائزة: ${reward} نقطة`,
                `💔 الخسارة: -${penalty} نقطة`,
                `🎌 يجب أن تكون شخصية أنمي حقيقية`,
                ``,
                `📝 اكتب اسم الشخصية`
            ];

            await sendMessage(sock, chatId, lines, msg, [sender]);

            let finished = false;

            const handler = async ({ messages }) => {
                if (finished) return;
                for (const m of messages) {
                    if (m.key.remoteJid !== chatId) continue;
                    const winner = m.key.participant || m.participant || m.key.remoteJid;
                    const txt = m.message?.conversation || m.message?.extendedTextMessage?.text || '';
                    if (!txt) continue;

                    const answer = txt.trim();

                    // التحقق من أنها تبدأ بالحرف المطلوب
                    if (!answer.startsWith(letter)) continue;

                    // التحقق من أنها شخصية أنمي موجودة
                    const isCharacter = animeCharacters.some(c => c === answer);
                    if (!isCharacter) continue;

                    finished = true;
                    clearTimeout(timeout);
                    sock.ev.off('messages.upsert', handler);

                    points[winner] = (points[winner] || 0) + reward;
                    saveJSON(pointsPath, points);

                    const resultLines = [
                        `🎉 *إجابة صحيحة!*`,
                        ``,
                        `🏆 الفائز: @${winner.split('@')[0]}`,
                        `🎌 الشخصية: *${answer}*`,
                        `🔤 الحرف: ${letter}`,
                        `⭐ +${reward} نقطة`,
                        `💰 نقاطك: ${points[winner]}`,
                        `🏅 رتبتك: ${getLevel(points[winner])}`,
                        ``,
                        `🥳 تهانينا!`
                    ];
                    await sendMessage(sock, chatId, resultLines, m, [winner]);
                    return;
                }
            };

            sock.ev.on('messages.upsert', handler);

            const timeout = setTimeout(async () => {
                if (finished) return;
                finished = true;
                sock.ev.off('messages.upsert', handler);

                // خصم من جميع المشاركين
                const metadata = await sock.groupMetadata(chatId);
                let deductedCount = 0;

                for (const participant of metadata.participants) {
                    const jid = participant.id;
                    if (jid !== sock.user.id) {
                        points[jid] = Math.max(0, (points[jid] || 0) - penalty);
                        deductedCount++;
                    }
                }

                saveJSON(pointsPath, points);

                const penaltyLines = [
                    `⏰ *انتهى الوقت!*`,
                    ``,
                    `🔤 الحرف كان: *${letter}*`,
                    ``,
                    `💔 تم خصم ${penalty} نقطة`,
                    ``,
                    `📌 حاول مرة أخرى مع .حرف`
                ];
                await sendMessage(sock, chatId, penaltyLines, msg);
            }, gameTime);

        } catch (error) {
            console.error('✗ خطأ في أمر حرف:', error);
            await sendMessage(sock, msg.key.remoteJid, [
                '❌ حدث خطأ أثناء تنفيذ الأمر.',
                '📌 حاول مرة أخرى لاحقاً.'
            ], msg);
        }
    }
};