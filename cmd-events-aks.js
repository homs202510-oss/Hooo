// ========== دالة الإرسال ==========
async function sendMessage(sock, chatId, lines, quoted = null, mentions = []) {
    if (!Array.isArray(lines)) {
        lines = [lines];
    }
    
    let msg = `🔁 فـعـالـيـة عـكـس الـكـلـمـة 🔁\n`;
    msg += `━━━━━━━━━━━━━━━━━━━━\n`;
    for (const line of lines) {
        msg += `${line}\n`;
    }
    msg += `━━━━━━━━━━━━━━━━━━━━\n`;
    msg += `𝘽𝙔┇𝑷𝑯𝑨𝑵𝑻𝑶𝑴 ❤️`;
    await sock.sendMessage(chatId, { text: msg, mentions }, { quoted: quoted });
}

module.exports = {
    command: 'عكس',
    description: '🔁 فعالية عكس الكلمة - اكتب الكلمة مقلوبة صح',
    usage: '.عكس [سهل|متوسط|صعب]',
    category: 'فعاليات',
    example: '.عكس سهل',

    async execute(sock, msg) {
        const chatId = msg.key.remoteJid;
        try {
            const sender = msg.key.participant || msg.participant || msg.key.remoteJid;
            const points = loadJSON(pointsPath);

            const body = msg.message?.conversation || msg.message?.extendedTextMessage?.text || '';
            const parts = body.trim().split(/\s+/);
            const inputLevel = (parts[1] || '').trim();

            const validLevels = ['سهل', 'متوسط', 'صعب'];
            if (!validLevels.includes(inputLevel)) {
                const lines = [
                    '❌ *المستوى غير صحيح!*',
                    '',
                    '📖 *المستويات المتاحة:*',
                    '🟢 سهل',
                    '🟡 متوسط',
                    '🔴 صعب',
                    '',
                    '💡 مثال: .عكس سهل'
                ];
                await sendMessage(sock, chatId, lines, msg, [sender]);
                return;
            }

            const levelWords = words[inputLevel];
            const word = levelWords[Math.floor(Math.random() * levelWords.length)];
            const answer = reverseWord(word.replace(/\s+/g, ''));

            // إرسال السؤال
            const lines = [
                `🔁 *اعكس الكلمة التالية:*`,
                ``,
                `*${word}*`,
                ``,
                `⏳ الوقت: ${timeMap[inputLevel] / 1000} ثانية`,
                `💰 الجائزة: 50 نقطة`,
                `💔 الخسارة: -50 نقطة`,
                `🏆 المستوى: ${inputLevel}`,
                ``,
                `📝 اكتب الكلمة مقلوبة`
            ];

            await sendMessage(sock, chatId, lines, msg, [sender]);

            let finished = false;

            const handler = async ({ messages }) => {
                if (finished) return;
                for (const m of messages) {
                    if (m.key.remoteJid !== chatId) continue;
                    const winner = m.key.participant || m.participant || m.key.remoteJid;
                    const txt = m.message?.conversation || m.message?.extendedTextMessage?.text || '';
                    if (!txt) continue;

                    const cleaned = txt.replace(/\s+/g, '');
                    if (cleaned === answer) {
                        finished = true;
                        clearTimeout(timeout);
                        sock.ev.off('messages.upsert', handler);

                        points[winner] = (points[winner] || 0) + 50;
                        saveJSON(pointsPath, points);

                        const resultLines = [
                            `🎉 *إجابة صحيحة!*`,
                            ``,
                            `🏆 الفائز: @${winner.split('@')[0]}`,
                            `🔁 الإجابة: *${answer}*`,
                            `⭐ +50 نقطة`,
                            `💰 نقاطك: ${points[winner]}`,
                            ``,
                            `🥳 تهانينا!`
                        ];
                        await sendMessage(sock, chatId, resultLines, m, [winner]);
                        return;
                    }
                }
            };

            sock.ev.on('messages.upsert', handler);

            const timeout = setTimeout(async () => {
                if (finished) return;
                finished = true;
                sock.ev.off('messages.upsert', handler);

                // خصم 50 نقطة من صاحب الأمر فقط
                const senderPoints = points[sender] || 0;
                points[sender] = Math.max(0, senderPoints - 50);
                saveJSON(pointsPath, points);

                const penaltyLines = [
                    `⏰ *انتهى الوقت!*`,
                    ``,
                    `🔁 الإجابة الصحيحة: *${answer}*`,
                    ``,
                    `💔 تم خصم 50 نقطة من @${sender.split('@')[0]}`,
                    `💰 نقاطك: ${points[sender]}`,
                    ``,
                    `📌 حاول مرة أخرى مع .عكس`
                ];
                await sendMessage(sock, chatId, penaltyLines, msg, [sender]);
            }, timeMap[inputLevel]);

        } catch (error) {
            console.error('✗ خطأ في أمر عكس:', error);
            await sendMessage(sock, msg.key.remoteJid, [
                '❌ حدث خطأ أثناء تنفيذ الأمر.',
                '📌 حاول مرة أخرى لاحقاً.'
            ], msg);
        }
    }
};