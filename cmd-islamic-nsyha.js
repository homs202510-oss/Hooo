// ========== الأمر الرئيسي ==========
module.exports = {
    command: ['نصائح', 'نصيحة'],
    description: '📿 نصائح دينية (نصائح) أو تحفيزية (نصيحة)',
    category: 'ديني',
    usage: '.نصائح ── نصائح دينية\n.نصيحة ── نصائح تحفيزية',

    async execute(sock, m) {
        try {
            const chatId = m.key.remoteJid;
            const sender = m.key.participant || m.key.remoteJid;
            const senderNumber = sender.split('@')[0];

            // ===== تحديد الأمر المستخدم =====
            const body = m.message?.conversation || m.message?.extendedTextMessage?.text || '';
            const commandUsed = body.trim().split(/\s+/)[0]?.replace('.', '') || '';

            let adviceList = [];
            let title = '';

            if (commandUsed === 'نصائح') {
                adviceList = religiousAdvice;
                title = 'نصائح دينية';
            } else if (commandUsed === 'نصيحة') {
                adviceList = motivationalAdvice;
                title = 'نصيحة تحفيزية';
            } else {
                // إذا كان الأمر غير معروف، نعرض المساعدة
                const lines = [
                    '📖 *الأوامر المتاحة:*',
                    '',
                    '📌 `.نصائح`  ──  نصائح دينية',
                    '📌 `.نصيحة`  ──  نصائح تحفيزية وملهمة'
                ];
                await sendMessage(sock, chatId, lines, m, [sender]);
                return;
            }

            // ===== اختيار نصيحة عشوائية =====
            const randomAdvice = adviceList[Math.floor(Math.random() * adviceList.length)];

            // ===== بناء الرسالة =====
            const lines = [
                `💡 *${title}* 💡`,
                '',
                `👤 @${senderNumber}`,
                '',
                `${randomAdvice}`
            ];

            await sendMessage(sock, chatId, lines, m, [sender]);

        } catch (error) {
            console.error('❌ خطأ في أمر نصائح:', error);
            await sendMessage(sock, m.key.remoteJid, [
                '❌ *حدث خطأ*',
                '',
                `📝 ${error.message || 'خطأ غير معروف'}`,
                '',
                '📌 حاول مرة أخرى لاحقاً'
            ], m);
        }
    }
};