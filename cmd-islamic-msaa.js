// مسائية.js - أذكار المساء المستحبة والمأثورة عن النبي ﷺ

// ========== دالة الإرسال الموحدة ==========
async function sendMessage(sock, chatId, lines, quoted = null, mentions = []) {
    if (!Array.isArray(lines)) {
        lines = [lines];
    }

    let msg = `🌙 أذكـار الـمـسـاء 🌙\n`;
    msg += `━━━━━━━━━━━━━━━━━━━━\n`;
    for (const line of lines) {
        if (line && line.trim()) {
            msg += `${line}\n`;
        }
    }
    msg += `━━━━━━━━━━━━━━━━━━━━\n`;
    msg += `𝘽𝙔┇𝑷𝑯𝑨𝑵𝑻𝑶𝑴 ❤️`;

    await sock.sendMessage(chatId, { text: msg, mentions }, { quoted: quoted });
}

module.exports = {
    command: ['مسائية', 'مساء'],
    description: '🌙 يعرض أذكار المساء المستحبة والمأثورة عن النبي ﷺ، للتحصين والذكر في آخر اليوم.',
    category: 'ديني',

    async execute(sock, m) {
        try {
            const chatId = m.key.remoteJid;

            const lines = [
                `🌙 *أذكار المساء* 🌙`,
                '',
                `✨ *الذكر الأول:*`,
                `اللهم بك أمسينا وبك أصبحنا وبك نحيا وبك نموت وإليك المصير.`,
                '',
                `✨ *الذكر الثاني:*`,
                `أمسينا وأمسى الملك لله، والحمد لله، لا إله إلا الله وحده لا شريك له، له الملك وله الحمد وهو على كل شيء قدير.`,
                '',
                `✨ *الذكر الثالث:*`,
                `اللهم إني أسألك خير هذه الليلة: فتحها، ونصرها، ونورها، وبركتها، وهداها، وأعوذ بك من شر ما فيها وشر ما بعدها.`,
                '',
                `✨ *الذكر الرابع:*`,
                `اللهم عافني في بدني، اللهم عافني في سمعي، اللهم عافني في بصري، لا إله إلا أنت.`,
                '',
                `✨ *الذكر الخامس:*`,
                `أعوذ بكلمات الله التامات من شر ما خلق. (3 مرات)`,
                '',
                `✨ *الذكر السادس:*`,
                `بسم الله الذي لا يضر مع اسمه شيء في الأرض ولا في السماء وهو السميع العليم. (3 مرات)`,
                '',
                `✨ *الذكر السابع:*`,
                `سورة الإخلاص، الفلق، الناس (3 مرات لكل سورة)`,
                '',
                `✨ *الذكر الثامن:*`,
                `رضيت بالله رباً، وبالإسلام ديناً، وبمحمد ﷺ نبياً ورسولاً.`,
                '',
                `✨ *الذكر التاسع:*`,
                `حسبي الله لا إله إلا هو عليه توكلت وهو رب العرش العظيم. (7 مرات)`,
                '',
                `✨ *الذكر العاشر:*`,
                `اللهم صل وسلم على نبينا محمد.`
            ];

            await sendMessage(sock, chatId, lines, m);

        } catch (error) {
            console.error('❌ خطأ في أمر مسائية:', error);
            await sendMessage(sock, m.key.remoteJid, [
                '❌ *حدث خطأ*',
                '',
                `📝 ${error.message || 'خطأ غير معروف'}`,
                '',
                '📌 حاول مرة أخرى لاحقاً'
            ], m);
        }
    }
};